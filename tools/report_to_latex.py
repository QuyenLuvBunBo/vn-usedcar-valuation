"""Turn `docs/report.md` into `docs/report.tex`.

The report is written once, in Markdown, and the PDF is produced from it. Converting by hand means two
copies of the same 6,600 words, and sooner or later a number changes in one and not the other — the exact
failure this project spends its time guarding against elsewhere. So the conversion is a command:

    python -m tools.report_to_latex                 # docs/report.md -> docs/report.tex
    cd docs && xelatex report.tex && xelatex report.tex

XeLaTeX (or LuaLaTeX) is required, not pdfLaTeX: the text carries Vietnamese province names and the
typographic characters `²`, `×`, `§`, `±`, `Δ`, `→`, `−`. `fontspec` with the DejaVu families handles all of
them, and DejaVu ships with TeX Live.

The output is deliberately plain: `article`, `booktabs` tables wrapped in `adjustbox` so the eleven-column
benchmark fits, floats pinned with `[H]` so tables stay where the prose puts them, and no colour beyond the
link colour. Nothing in here decides content — headings, tables, figures, numbers all come from the Markdown.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

REPO = Path(__file__).resolve().parents[1]

PREAMBLE = r"""% !TEX program = xelatex
% Analysis 2 (M2, week 3) report -- generated from docs/report.md by
%     python -m tools.report_to_latex
% Do not edit this file by hand: edit the Markdown and regenerate, or the two will drift apart.
%
% ---- Overleaf ----
% Overleaf compiles with pdfLaTeX by default and ignores the magic comment above, so set it by hand:
%   1. Menu (top left) -> Settings -> Compiler -> XeLaTeX
%   2. Menu -> Main document -> report.tex   (otherwise Overleaf keeps compiling main.tex)
%   3. upload the five PNGs into a folder named exactly `figures/`, or the images come out missing
%   4. Recompile twice: the contents page and the figure numbers need a second pass
%
% ---- locally ----
%     cd docs && xelatex report.tex && xelatex report.tex
% XeLaTeX or LuaLaTeX is required: the text carries Vietnamese province names and the symbols
% ² × § ± Δ → −, which pdfLaTeX with T1 encoding cannot set.
\documentclass[11pt,a4paper]{article}
\usepackage{iftex}
\ifPDFTeX
  \errmessage{This report must be compiled with XeLaTeX or LuaLaTeX: it uses fontspec, Vietnamese
    province names and the symbols 2^2, x, SS, +/-, Delta, arrow. In Overleaf: Menu > Settings >
    Compiler > XeLaTeX, then Menu > Main document > report.tex.}
\fi
\usepackage[margin=2.3cm,top=2.5cm,bottom=2.5cm,footskip=1.1cm]{geometry}
\usepackage{fontspec}
\setmainfont{DejaVu Serif}
\setsansfont{DejaVu Sans}
\setmonofont[Scale=0.86]{DejaVu Sans Mono}
\usepackage{booktabs}
\usepackage{array}
\usepackage{adjustbox}
\usepackage{float}
\usepackage{graphicx}
\usepackage{enumitem}
\usepackage{listings}
\usepackage{xcolor}
\usepackage{fancyhdr}
\usepackage{caption}
\usepackage[hidelinks]{hyperref}
\graphicspath{{figures/}}
\captionsetup{font=small,labelfont=bf,skip=4pt}
\setlist[itemize]{leftmargin=1.4em,itemsep=2pt,topsep=3pt,parsep=0pt}
\setlist[enumerate]{leftmargin=1.7em,itemsep=2pt,topsep=3pt,parsep=0pt}
\setlength{\parskip}{4pt}
\setlength{\parindent}{0pt}
\pagestyle{fancy}
\fancyhf{}
\fancyhead[L]{\small Analysis 2 (M2, week 3)}
\fancyhead[R]{\small\thepage}
\renewcommand{\headrulewidth}{0.4pt}
\lstset{basicstyle=\ttfamily\footnotesize,breaklines=true,frame=single,
        framerule=0.3pt,rulecolor=\color{black!40},backgroundcolor=\color{black!3},
        columns=fullflexible,keepspaces=true,showstringspaces=false,
        aboveskip=6pt,belowskip=6pt}
\title{\bfseries Analysis 2 report (M2, week 3)\\[2pt]
       \large used-car valuation and listing screening}
% TODO: put the team names on the line below before submitting.
\author{Week 3 team}
\date{8 November 2026}

\begin{document}
\maketitle
\thispagestyle{empty}
"""

SPECIALS = {
    "\\": r"\textbackslash{}",
    "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
    "{": r"\{", "}": r"\}",
    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def escape(text: str) -> str:
    """Escape LaTeX specials in plain prose. Applied to text segments only, never to generated markup."""
    return "".join(SPECIALS.get(char, char) for char in text)


def inline(text: str) -> str:
    """Markdown inline markup in three passes: **bold**, then `code`, then *italic* + escaping.

    Bold has to be found first: `**`body_type` is missing**` puts code inside bold, and a code-first pass
    would leave the two asterisks in different pieces of the string.
    """
    out, position = [], 0
    for match in re.finditer(r"\*\*(.+?)\*\*", text, re.S):
        out.append(inline_code(text[position:match.start()]))
        out.append(r"\textbf{" + inline_code(match.group(1)) + "}")
        position = match.end()
    out.append(inline_code(text[position:]))
    return "".join(out)


def inline_code(text: str) -> str:
    """`code` spans -> \texttt{}, everything else handed to the italic/escape pass."""
    out = []
    for part in re.split(r"(`[^`]*`)", text):
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            out.append(r"\texttt{" + escape(part[1:-1]) + "}")
        else:
            out.append(inline_plain(part))
    return "".join(out)


def inline_plain(text: str) -> str:
    """Italic and plain text; the report does not nest bold inside bold."""
    out = []
    for chunk in re.split(r"(\*[^*]+\*)", text):
        if chunk.startswith("*") and chunk.endswith("*") and len(chunk) > 2:
            out.append(r"\emph{" + escape(chunk[1:-1]) + "}")
        else:
            out.append(escape(chunk))
    return "".join(out)


NUMERIC = re.compile(r"^[−\-–—]?[\d.,]+%?$|^—$|^−$")
ITEM = re.compile(r"^- (.*)$")
NUMBERED = re.compile(r"^(\d+)\. (.*)$")


def is_numeric_column(cells: list[str]) -> bool:
    values = [re.sub(r"[`*]", "", cell).strip() for cell in cells if cell.strip()]
    return bool(values) and all(NUMERIC.match(value) for value in values)


def table_latex(block: list[str]) -> str:
    """One Markdown table -> booktabs tabular, column alignment inferred from the data."""
    rows = [[cell.strip() for cell in line.strip().strip("|").split("|")] for line in block]
    header, body = rows[0], rows[2:]
    width = len(header)
    alignment = []
    for index in range(width):
        column = [row[index] for row in body if index < len(row)]
        alignment.append("r" if is_numeric_column(column) else "l")
    lines = [r"\begin{table}[H]", r"\centering", r"\footnotesize",
             r"\setlength{\tabcolsep}{4pt}",
             r"\begin{adjustbox}{max width=\textwidth}",
             r"\begin{tabular}{@{}" + "".join(alignment) + r"@{}}", r"\toprule"]
    lines.append(" & ".join(inline(cell) for cell in header) + r" \\")
    lines.append(r"\midrule")
    for row in body:
        cells = row + [""] * (width - len(row))
        lines.append(" & ".join(inline(cell) for cell in cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}", r"\end{table}", ""]
    return "\n".join(lines)


def list_latex(items: list[tuple[str, str]]) -> str:
    """A run of list items: `itemize` for dashes, `enumerate` for numbers."""
    if not items:
        return ""
    ordered = items[0][0] == "ol"
    lines = [r"\begin{enumerate}" if ordered else r"\begin{itemize}"]
    for _, text in items:
        lines.append(r"  \item " + inline(text))
    lines.append(r"\end{enumerate}" if ordered else r"\end{itemize}")
    lines.append("")
    return "\n".join(lines)


def convert(markdown: str) -> str:
    """Walk the Markdown once and emit LaTeX. Blocks are handled by kind, in document order."""
    lines = markdown.split("\n")
    out: list[str] = []
    paragraph: list[str] = []
    items: list[tuple[str, str]] = []
    index = 0

    def flush_paragraph() -> None:
        if paragraph:
            out.append(inline(" ".join(part.strip() for part in paragraph)))
            out.append("")
            paragraph.clear()

    def flush_list() -> None:
        if items:
            out.append(list_latex(items))
            items.clear()

    while index < len(lines):
        line = lines[index]
        stripped = line.strip()

        if stripped.startswith("```"):
            flush_paragraph()
            flush_list()
            index += 1
            block = []
            while index < len(lines) and not lines[index].strip().startswith("```"):
                block.append(lines[index])
                index += 1
            index += 1
            out += [r"\begin{lstlisting}", *block, r"\end{lstlisting}", ""]
            continue

        if stripped.startswith("|"):
            flush_paragraph()
            flush_list()
            block = []
            while index < len(lines) and lines[index].strip().startswith("|"):
                block.append(lines[index])
                index += 1
            out.append(table_latex(block))
            continue

        if stripped.startswith("!["):
            flush_paragraph()
            flush_list()
            match = re.match(r"!\[(.*?)\]\((.*?)\)", stripped)
            if match:
                alt, path = match.group(1), match.group(2)
                out += [r"\begin{figure}[H]", r"\centering",
                        r"\includegraphics[width=\textwidth]{" + path + "}",
                        r"\caption{" + inline(alt) + "}", r"\end{figure}", ""]
            index += 1
            continue

        if stripped.startswith("#"):
            flush_paragraph()
            flush_list()
            if stripped.startswith("### "):
                title = re.sub(r"^###\s+", "", stripped)
                title = re.sub(r"^\d+(?:\.\d+)+\s+", "", title)
                out += [r"\subsection{" + inline(title) + "}", ""]
            elif stripped.startswith("## "):
                title = re.sub(r"^##\s+", "", stripped)
                if title == "Abstract":
                    index += 1
                    body: list[str] = []
                    while index < len(lines) and not lines[index].strip().startswith("#"):
                        body.append(lines[index])
                        index += 1
                    text = " ".join(part.strip() for part in body if part.strip())
                    out += [r"\begin{abstract}", inline(text), r"\end{abstract}", ""]
                    continue
                if title == "Headline numbers":
                    out += [r"\section*{" + inline(title) + "}",
                            r"\addcontentsline{toc}{section}{" + inline(title) + "}", ""]
                elif title.startswith("Appendix "):
                    if r"\appendix" not in out:
                        out.append(r"\appendix")
                    title = re.sub(r"^Appendix\s+[A-Z]\s*[—-]\s*", "", title)
                    out += [r"\section{" + inline(title) + "}", ""]
                else:
                    title = re.sub(r"^\d+\.\s+", "", title)
                    out += [r"\section{" + inline(title) + "}", ""]
            index += 1
            continue

        if not stripped:
            flush_paragraph()
            flush_list()
            index += 1
            continue

        numbered = NUMBERED.match(stripped)
        dashed = ITEM.match(stripped)
        if numbered or dashed:
            flush_paragraph()
            kind = "ol" if numbered else "ul"
            if items and items[0][0] != kind:
                flush_list()
            items.append((kind, numbered.group(2) if numbered else dashed.group(1)))
            index += 1
            while index < len(lines):
                following = lines[index]
                if not following.strip():
                    break
                if NUMBERED.match(following.strip()) or ITEM.match(following.strip()):
                    break
                if not following.startswith("  "):
                    break
                kind_now, text = items[-1]
                items[-1] = (kind_now, text + " " + following.strip())
                index += 1
            continue

        paragraph.append(line)
        index += 1

    flush_paragraph()
    flush_list()
    return "\n".join(out)




def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Convert the Markdown report to LaTeX")
    parser.add_argument("--source", default=str(REPO / "docs" / "report.md"))
    parser.add_argument("--target", default=str(REPO / "docs" / "report.tex"))
    args = parser.parse_args(argv)

    source, target = Path(args.source), Path(args.target)
    body = convert(source.read_text(encoding="utf-8"))
    document = PREAMBLE + body + "\n\\end{document}\n"
    # Contents page goes after the abstract: title, abstract, contents, then the report itself.
    anchor = "\\end{abstract}"
    contents = "\n\\tableofcontents\n\\newpage\n"
    if anchor in document:
        document = document.replace(anchor, anchor + contents, 1)
    else:
        document = document.replace("\\thispagestyle{empty}", "\\thispagestyle{empty}" + contents, 1)
    target.write_text(document, encoding="utf-8", newline="\n")
    print(f"{source.name} -> {target.name}: {len(document.splitlines())} lines, "
          f"{document.count('begin{')} environments")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
