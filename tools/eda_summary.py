"""Exploratory data analysis on the merged dataset: the numbers and the five figures for report §3.

Everything is computed from `data/master/master_clean_dataset.csv` (100,887 merged, de-duplicated
listings) inside a documented price window, and every table is regenerated by one command, so the
report can cite a number and a reader can reproduce it.

Run:
    python -m tools.eda_summary
    python -m tools.eda_summary --min-price 10000000 --max-price 50000000000
"""

from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.common import config  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
MIN_PRICE = 10_000_000
MAX_PRICE = 50_000_000_000
# Spellings of one province that differ by more than case or diacritics, so folding cannot merge them.
PROVINCE_ALIASES = {
    "TP HCM": "TP. Hồ Chí Minh",
    "TP.HCM": "TP. Hồ Chí Minh",
    "TP.Hồ Chí Minh": "TP. Hồ Chí Minh",
    "HCM": "TP. Hồ Chí Minh",
}
SEGMENT_EXCLUDE = ("Unknown", "Other")
# The table and figure 4 cover this range; anything outside it but still plausible is older stock.
FIRST_MODEL_YEAR = 2010
LAST_MODEL_YEAR = 2026
# Outside this range a manufacture year cannot be real: the snapshot carries 1025, 2028, 2030 and 2032.
PLAUSIBLE_FIRST, PLAUSIBLE_LAST = 1980, LAST_MODEL_YEAR


def _fold(text: str) -> str:
    """Case- and diacritic-insensitive key, so 'Đăk Lăk' and 'Đắk Lăk' collapse to one province."""
    decomposed = unicodedata.normalize("NFD", str(text))
    stripped = "".join(char for char in decomposed if not unicodedata.combining(char))
    return "".join(char for char in stripped.casefold() if char.isalnum() or char == " ").strip()


def canonical_province(series: pd.Series) -> pd.Series:
    """Merge spelling variants; the most frequent surface form wins as the display name."""
    values = series.fillna("Unknown").astype(str).str.strip().replace(PROVINCE_ALIASES)
    keys = values.map(_fold)
    display = values.groupby(keys).agg(lambda column: column.value_counts().index[0])
    return keys.map(display).fillna(values)


def _save(fig, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    fig.clf()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="EDA summary and figures for report §3")
    parser.add_argument("--master", default=str(config.DATA_MASTER / "master_clean_dataset.csv"))
    parser.add_argument("--doc", default="docs/eda_summary.md")
    parser.add_argument("--figures", default="docs/figures")
    parser.add_argument("--min-price", type=int, default=MIN_PRICE)
    parser.add_argument("--max-price", type=int, default=MAX_PRICE)
    args = parser.parse_args(argv)

    raw = pd.read_csv(args.master, low_memory=False)
    raw["location_province"] = canonical_province(raw["location_province"])
    total = len(raw)
    raw_chotot = (raw["source_platform"] == "chotot").sum()
    frame = raw[raw["price_vnd"].between(args.min_price, args.max_price)].copy()
    dropped = total - len(frame)
    frame["price_per_1000km"] = frame["price_vnd"] / (frame["mileage_km"].clip(lower=1) / 1000)
    segment = frame["body_type"].fillna("Unknown")

    figures = Path(args.figures)
    if not figures.is_absolute():
        figures = REPO / figures
    doc = Path(args.doc)
    if not doc.is_absolute():
        doc = REPO / doc

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axis = plt.subplots(figsize=(7, 4))
    axis.hist(np.log10(frame["price_vnd"]), bins=60, color="#3b6ea5")
    axis.set_xlabel("log10(asking price, VND)")
    axis.set_ylabel("listings")
    axis.set_title(f"Asking price, {len(frame):,} listings")
    _save(fig, figures / "fig1_price_distribution.png")

    order = frame.groupby("source_platform")["price_vnd"].median().sort_values().index
    groups = [np.log10(frame.loc[frame["source_platform"] == name, "price_vnd"]) for name in order]
    fig, axis = plt.subplots(figsize=(8, 4.5))
    axis.boxplot(groups, tick_labels=list(order), showfliers=False)
    axis.set_ylabel("log10(asking price, VND)")
    axis.set_title("Price spread between platforms (whiskers only)")
    axis.tick_params(axis="x", rotation=25)
    _save(fig, figures / "fig2_price_by_source.png")

    by_province = (frame.groupby("location_province")
                   .agg(listings=("price_vnd", "size"), median_price=("price_vnd", "median"))
                   .sort_values("listings", ascending=False).head(12))
    fig, axis = plt.subplots(figsize=(7, 5))
    axis.barh(by_province.index[::-1], by_province["median_price"][::-1] / 1e9, color="#4f8a5b")
    axis.set_xlabel("median asking price (billion VND)")
    axis.set_title("Median price by province — top 12 by volume")
    _save(fig, figures / "fig3_price_by_province.png")

    by_year_frame = frame[frame["manufacture_year"].between(FIRST_MODEL_YEAR, LAST_MODEL_YEAR)]
    by_year = by_year_frame.groupby("manufacture_year")["price_vnd"].median()
    implausible = frame[~frame["manufacture_year"].between(PLAUSIBLE_FIRST, PLAUSIBLE_LAST)]
    implausible_values = sorted(int(year) for year in implausible["manufacture_year"].dropna().unique())
    older = frame[frame["manufacture_year"].between(PLAUSIBLE_FIRST, FIRST_MODEL_YEAR - 1)]
    fig, axis = plt.subplots(figsize=(7, 4))
    axis.plot(by_year.index, by_year.to_numpy() / 1e9, marker="o", color="#a55a3b")
    axis.set_xlabel("manufacture year")
    axis.set_ylabel("median asking price (billion VND)")
    axis.set_title("Median price by model year")
    _save(fig, figures / "fig4_price_by_year.png")

    segments = [name for name in segment.value_counts().index if name not in SEGMENT_EXCLUDE][:8]
    series = [frame.loc[segment == name, "price_per_1000km"].dropna().clip(upper=3_000_000_000) / 1e6
              for name in segments]
    fig, axis = plt.subplots(figsize=(8, 4.5))
    axis.boxplot(series, tick_labels=segments, showfliers=False)
    axis.set_ylabel("million VND per 1000 km")
    axis.set_title("Price per 1000 km by body type")
    axis.tick_params(axis="x", rotation=25)
    _save(fig, figures / "fig5_price_per_km_by_segment.png")

    by_source = (frame.groupby("source_platform")
                 .agg(listings=("price_vnd", "size"), median_price=("price_vnd", "median"),
                      p25=("price_vnd", lambda column: column.quantile(0.25)),
                      p75=("price_vnd", lambda column: column.quantile(0.75)),
                      median_price_per_1000km=("price_per_1000km", "median"))
                 .sort_values("listings", ascending=False))
    by_segment = (frame.assign(segment=segment).groupby("segment")
                  .agg(listings=("price_vnd", "size"), median_price=("price_vnd", "median"),
                       median_price_per_1000km=("price_per_1000km", "median"))
                  .sort_values("listings", ascending=False))
    by_province_all = by_province.assign(
        median_price_billion=(by_province["median_price"] / 1e9).round(3))
    spread = by_source[by_source["listings"] >= 500]
    if spread.empty:                       # no platform is big enough: the comparison is meaningless
        spread = by_source
    cheapest = spread["median_price"].idxmin()
    dearest = spread["median_price"].idxmax()
    lines = [
        "# EDA summary — merged dataset", "",
        f"Source: `data/master/master_clean_dataset.csv`, **{total:,} merged listings**. The price window "
        f"**{args.min_price:,} – {args.max_price:,} VND** keeps **{len(frame):,}** rows and drops "
        f"**{dropped:,}** ({dropped / total:.2%}) that are placeholders, deposits or typos — the raw "
        "maximum is 465 trillion VND (`log1p` 33.8). Figures live in `docs/figures/`.", "",
        "Province names are canonicalised before counting (case- and diacritic-insensitive folding plus an "
        "explicit alias table), so `TP HCM` / `TP.HCM` fold into `TP. Hồ Chí Minh` and `Đăk Lăk` / `Đắk Lăk` "
        "become one province. Without that step the largest market is split in two and every regional "
        "number is wrong.", "",
        "## Volume and price by platform", "",
        "| Platform | Listings | Median price (VND) | IQR P25–P75 (VND) | Median per 1000 km (VND) |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for name, row in by_source.iterrows():
        lines.append(f"| {name} | {int(row['listings']):,} | {int(row['median_price']):,} | "
                     f"{int(row['p25']):,} – {int(row['p75']):,} | "
                     f"{int(row['median_price_per_1000km']):,} |")
    lines += ["", f"Chợ Tốt alone contributes **{int(by_source.loc['chotot', 'listings']):,}** listings inside the "
              f"window — {int(raw_chotot):,} before the price filter "
              f"({by_source.loc['chotot', 'listings'] / len(frame):.1%} of the window). Among platforms with "
              f"at least 500 listings the median asking price runs from "
              f"**{int(spread.loc[cheapest, 'median_price']):,}** ({cheapest}) to "
              f"**{int(spread.loc[dearest, 'median_price']):,}** ({dearest}) — a factor of "
              f"{spread.loc[dearest, 'median_price'] / spread.loc[cheapest, 'median_price']:.2f}. §6 therefore "
              "reports error per platform instead of quoting a single MAPE.", "",
              "## Median price by province (top 12 by volume)", "",
              "| Province | Listings | Median price (billion VND) |", "| --- | ---: | ---: |"]
    for name, row in by_province_all.iterrows():
        lines.append(f"| {name} | {int(row['listings']):,} | {row['median_price_billion']:.3f} |")
    top_two = int(by_province["listings"].head(2).sum())
    province_ratio = (by_province_all["median_price_billion"].max()
                      / by_province_all["median_price_billion"].min())
    lines += ["", f"The top two provinces carry **{top_two:,}** of {len(frame):,} listings "
              f"({top_two / len(frame):.0%}); across the top 12 the median price differs by "
              f"**{province_ratio:.1f}×** between the cheapest and the dearest market.", "",
              "## Segment (body type)", "",
              "| Segment | Listings | Median price (VND) | Median per 1000 km (VND) |",
              "| --- | ---: | ---: | ---: |"]
    for name, row in by_segment.iterrows():
        lines.append(f"| {name} | {int(row['listings']):,} | {int(row['median_price']):,} | "
                     f"{int(row['median_price_per_1000km']):,} |")
    unknown_share = (by_segment.loc["Unknown", "listings"] / len(frame)
                     if "Unknown" in by_segment.index else 0.0)
    lines += ["", f"`body_type` is unknown for **{unknown_share:.1%}** of the window — a data limitation, not "
              "a modelling choice: a fifth of the market cannot be assigned to a segment at all.", "",
              "## Median price by model year", "",
              f"The table and figure 4 cover **{FIRST_MODEL_YEAR}–{LAST_MODEL_YEAR}**, which is "
              f"{len(by_year_frame):,} listings. {len(older):,} listings are older stock "
              f"({PLAUSIBLE_FIRST}–{FIRST_MODEL_YEAR - 1}) and sit outside that window; "
              f"{len(implausible):,} rows carry a manufacture year that cannot be real "
              f"({', '.join(str(year) for year in implausible_values)}) and are data-entry errors.", "",
              "| Year | Median price (VND) |", "| ---: | ---: |"]
    for year, value in by_year.items():
        lines.append(f"| {int(year)} | {int(value):,} |")
    lines += ["", "## Reading", "",
              "- Price is right-skewed even inside the window, which is why every model fits "
              "`log1p(price_vnd)` and why R²(VND) always looks better than R²(log).",
              "- Platform medians differ by the factor measured above and regional medians by the ratio "
              "measured above. Both are real signal, and both are reasons to break error down by segment.",
              "- Price per 1000 km separates the segments far less than absolute price does: a cheap car is "
              "not cheap per kilometre, and mileage alone is a weak pricing signal. The feature ablation in "
              "§4 agrees — dropping `mileage_km` and `km_per_year` costs ΔR² = 0.0001.",
              "- Figures: `fig1_price_distribution.png`, `fig2_price_by_source.png`, "
              "`fig3_price_by_province.png`, `fig4_price_by_year.png`, `fig5_price_per_km_by_segment.png`.", ""]
    doc.parent.mkdir(parents=True, exist_ok=True)
    doc.write_text("\n".join(lines), encoding="utf-8", newline="\n")

    print(f"rows {total:,} | in window {len(frame):,} | dropped {dropped:,} | provinces "
          f"{frame['location_province'].nunique()} | segments {frame['body_type'].nunique()}")
    print(f"  figures -> {figures}")
    print(f"  doc     -> {doc}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
