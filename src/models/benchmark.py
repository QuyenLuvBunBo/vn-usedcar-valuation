"""Render docs/benchmark.md from data/master/model_results.json — no hand-typed numbers.

The report's §5 table must be a *copy* of what the training runs produced, never a re-derivation,
so this tool reads the results file and writes the Markdown table. It refuses to render a table
whose rows mix feature variants without saying so, and it keeps the test column to the rows that
actually carry one (the single M2 evaluation).

    python -m src.models.benchmark                    # all rows -> docs/benchmark.md
    python -m src.models.benchmark --features full   # one variant
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from src.common import config  # noqa: E402

RESULTS_PATH = config.DATA_MASTER / "model_results.json"
OUT_PATH = config.ROOT / "docs" / "benchmark.md"

MODEL_LABELS = {
    "median": "Median by brand\\|model\\|year",
    "ridge": "Ridge (target-encoded)",
    "rf": "Random Forest (300 trees)",
    "lgbm": "LightGBM",
    "catboost": "CatBoost",
    "xgboost": "XGBoost",
}


def render(rows: list[dict], variant: str) -> tuple[str, int]:
    """Markdown for the benchmark table + the per-model notes that justify each row."""
    chosen = [r for r in rows if r.get("features") == variant] if variant else list(rows)
    # a re-run of the same model+features+seed+split (e.g. to export predictions) appends a row
    # by contract; the table shows the latest of each, never two identical rows
    latest: dict[tuple, dict] = {}
    for row in chosen:
        latest[(row["model"], row["features"], row.get("seed"), row.get("split"))] = row
    chosen = list(latest.values())
    val_rows = [r for r in chosen if r.get("split") == "val"]
    test_rows = [r for r in chosen if r.get("split") == "test"]
    best = max(val_rows, key=lambda r: r["r2_log"], default=None)

    lines = [
        "# Benchmark — model comparison on the frozen split", "",
        f"Generated by `python -m src.models.benchmark` from `{RESULTS_PATH.name}` "
        f"({len(chosen)} rows); every number is a copy of a training run, never re-typed.", "",
        "Target `log1p(price_vnd)`; metrics in log space (R², RMSE) and VND (MAE, MAPE). "
        "Feature variant: **" + (variant or "all (mixed — see the rows)") + "**. "
        "The canary to beat: R²(log) 0.946 / MAPE 11.6 % (`tools.baseline_smoke`).", "",
        "| Model | Features | Seed | R² (log) | RMSE (log) | MAE (VND) | MAPE | fit (s) |",
        "|---|---|---|---:|---:|---:|---:|---:|",
    ]
    for row in sorted(val_rows, key=lambda r: -r["r2_log"]):
        lines.append(
            f"| {MODEL_LABELS.get(row['model'], row['model'])} | {row['features']} "
            f"| {row.get('seed', '')} | {row['r2_log']:.4f} | {row['rmse_log']:.4f} "
            f"| {row['mae_vnd']:,} | {row['mape']:.3f} | {row.get('seconds', '')} |")
    lines.append("")

    if best:
        lines += [f"Highest R²(log) on validation: **{MODEL_LABELS.get(best['model'], best['model'])}** "
                  f"(R²(log) {best['r2_log']}, MAPE {best['mape']:.3f}).", ""]
    beats = [r for r in val_rows if r["r2_log"] > 0.946 and r["mape"] < 0.116]
    if beats:
        names = ", ".join(MODEL_LABELS.get(r["model"], r["model"]) for r in beats)
        lines += [f"Models beating the canary on **both** headline metrics (R²(log) > 0.946 and "
                  f"MAPE < 11.6 %): {names}. **LightGBM** was shortlisted for the single test "
                  "evaluation on that rule — CatBoost has the higher R² but misses the MAPE bar, "
                  "and the P10/P90 intervals come from the same LightGBM family.", ""]

    lines += ["## Test evaluation (single, at M2)", ""]
    if test_rows:
        for row in test_rows:
            lines += [f"- **{MODEL_LABELS.get(row['model'], row['model'])}** "
                      f"({row['features']}, seed {row.get('seed')}): R²(log) {row['r2_log']}, "
                      f"RMSE(log) {row['rmse_log']}, MAE {row['mae_vnd']:,} VND, "
                      f"MAPE {row['mape']:.3f}."
                      + (f" 80 % interval coverage on test: "
                         f"{row['interval_coverage_80']}." if row.get("interval_coverage_80")
                         is not None else ""), ""]
    else:
        lines += ["_No test row yet — the test set is evaluated exactly once, at M2._", ""]

    if best and best.get("interval_coverage_80") is not None:
        lines += [f"80 % interval (LightGBM quantile P10/P90) empirical coverage on val: "
                  f"{best['interval_coverage_80']}.", ""]
    elif any(r.get("interval_coverage_80") is not None for r in val_rows):
        cover = [r for r in val_rows if r.get("interval_coverage_80") is not None][0]
        lines += [f"80 % interval (LightGBM quantile P10/P90) empirical coverage on val: "
                  f"{cover['interval_coverage_80']}.", ""]

    notes = [r for r in chosen if r.get("note")]
    if notes:
        lines += ["## Per-run notes", ""]
        for row in notes:
            lines.append(f"- `{row['model']}/{row['features']}`: {row['note']}")
        lines.append("")
    lines += ["Asking prices are advertised prices, not transaction prices.", ""]
    return "\n".join(lines), len(chosen)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="model_results.json -> docs/benchmark.md")
    parser.add_argument("--features", default="full", choices=("minimal", "full", "all"))
    args = parser.parse_args(argv)

    if not RESULTS_PATH.exists():
        raise SystemExit(f"missing {RESULTS_PATH} -> run 'python -m src.models.train' first")
    rows = json.loads(RESULTS_PATH.read_text(encoding="utf-8"))
    variants = sorted({r.get("features", "?") for r in rows})
    if args.features == "all" and len(variants) > 1:
        print(f"note: rows mix variants {variants} — render one at a time to keep the table honest")

    markdown, shown = render(rows, None if args.features == "all" else args.features)
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(markdown, encoding="utf-8")
    print(f"wrote {OUT_PATH} ({shown} benchmark rows from {len(rows)} logged runs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
